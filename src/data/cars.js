export const carById = (id) => {
    return (
        CARS.find((c) => {
            return c.id === id;
        }) ?? CARS[0]
    );
};

/** Display label of a gear index (0 = neutral). */
export function gearLabel(car, gear) {
    if (gear === 0) return 'N';
    return car.drivetrain.gearLabels?.[gear - 1] ?? String(gear);
}
